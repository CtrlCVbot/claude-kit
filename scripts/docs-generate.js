function genHooks() {
  const rows = [];
  for (const domain of listDomains()) {
    const dir = path.join(SRC_CLAUDE, domain, 'hooks');
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (!f.endsWith('.js')) continue;
      const full = path.join(dir, f);
      const js = fs.readFileSync(full, 'utf8');
      const info = parseHookHeader(js);
      rows.push({
        domain,
        name: f.replace(/\.js$/, ''),
        hook: info.hook || '—',
        event: info.event || '—',
        action: info.action || '—',
        source: relFromRoot(full),
      });
    }
  }

  let out = HEADER('Hooks', '`src/claude/*/hooks/*.js` (header JSDoc comment)');
  out += `전체 ${rows.length}개. 각 hook 파일 상단 JSDoc의 \`Hook/Event/Action\` 라인에서 추출.\n\n`;
  const byDomain = rows.reduce((acc, r) => {
    (acc[r.domain] ||= []).push(r);
    return acc;
  }, {});
  for (const domain of Object.keys(byDomain).sort()) {
    out += `## ${domain} 도메인\n\n`;
    out += `| Hook | Event | Action | Source |\n|---|---|---|---|\n`;
    for (const r of byDomain[domain]) {
      out += `| \`${r.name}\` | ${r.event} | ${r.action} | [${r.source}](../../${r.source}) |\n`;
    }
    out += '\n';
  }
  return out;
}

function genRules() {
  const rows = [];
  for (const domain of listDomains()) {
    const dir = path.join(SRC_CLAUDE, domain, 'rules');
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (!f.endsWith('.md')) continue;
      const full = path.join(dir, f);
      const md = fs.readFileSync(full, 'utf8');
      const lines = md.split('\n');
      const title = (lines.find(l => l.startsWith('# ')) || '').replace(/^# /, '').trim();
      const blockquote = lines.find(l => l.trim().startsWith('>')) || '';
      const summary = blockquote
        .replace(/^>\s*/, '')
        .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
        .trim()
        .slice(0, 160);
      rows.push({
        domain,
        name: title || f.replace(/\.md$/, ''),
        summary,
        source: relFromRoot(full),
      });
    }
  }

  let out = HEADER('Rules', '`src/claude/*/rules/*.md`');
  out += `전체 ${rows.length}개. 각 rule 문서의 h1 + 첫 blockquote 에서 추출.\n\n`;
  const byDomain = rows.reduce((acc, r) => {
    (acc[r.domain] ||= []).push(r);
    return acc;
  }, {});
  for (const domain of Object.keys(byDomain).sort()) {
    out += `## ${domain} 도메인\n\n`;
    out += `| Rule | Summary | Source |\n|---|---|---|\n`;
    for (const r of byDomain[domain]) {
      out += `| \`${r.name}\` | ${r.summary || '—'} | [${r.source}](../../${r.source}) |\n`;
    }
    out += '\n';
  }
  return out;
}

function genPairing() {
  if (!fs.existsSync(PAIRING_PATH)) {
    return HEADER('Pairing Registry', '`src/pairing-registry.json`') +
      '_pairing-registry.json 미존재._\n';
  }
  const reg = JSON.parse(fs.readFileSync(PAIRING_PATH, 'utf8'));
  const entries = (reg.entries || []).slice().sort((a, b) =>
    `${a.domain}-${a.type}-${a.identity}`.localeCompare(`${b.domain}-${b.type}-${b.identity}`)
  );

  let out = HEADER('Pairing Registry', '`src/pairing-registry.json`');
  out += `전체 ${entries.length} entries. Claude ↔ Codex 자산 페어링 상태.\n\n`;

  const statusCount = entries.reduce((acc, e) => {
    acc[e.status] = (acc[e.status] || 0) + 1;
    return acc;
  }, {});
  out += `## Status 요약\n\n`;
  for (const [k, v] of Object.entries(statusCount).sort()) {
    out += `- **${k}**: ${v}\n`;
  }
  out += '\n';

  const byDomain = entries.reduce((acc, e) => {
    (acc[e.domain] ||= []).push(e);
    return acc;
  }, {});
  for (const domain of Object.keys(byDomain).sort()) {
    out += `## ${domain} 도메인\n\n`;
    out += `| Identity | Type | Status | PrimaryCodex | Transition | Drift | Claude | Codex | CodexSkill |\n|---|---|---|---|---|---|---|---|---|\n`;
    for (const e of byDomain[domain]) {
      const claude = e.claude ? `\`${toPosix(e.claude)}\`` : '—';
      const codex = e.codex ? `\`${toPosix(e.codex)}\`` : '—';
      const codexSkill = e.codexSkill ? `\`${toPosix(e.codexSkill)}\`` : '—';
      out += `| \`${e.identity}\` | ${e.type} | ${e.status} | ${e.primaryCodex || '—'} | ${e.transitionState || '—'} | ${e.driftStatus || '—'} | ${claude} | ${codex} | ${codexSkill} |\n`;
    }
    out += '\n';
  }
  return out;
}

// -----------------------------------------------------------------
// Main
// -----------------------------------------------------------------

function main() {
  const isCheck = process.argv.includes('--check');
  const tasks = [
    { dir: REF_DIR, out: '01-commands.md', fn: genCommands },
    { dir: REF_DIR, out: '02-agents.md', fn: genAgents },
    { dir: REF_DIR, out: '03-skills.md', fn: genSkills },
    { dir: REF_DIR, out: '04-hooks.md', fn: genHooks },
    { dir: REF_DIR, out: '05-rules.md', fn: genRules },
    { dir: REF_DIR, out: '07-pairing-registry.md', fn: genPairing },
    { dir: SYNC_GUIDE_DIR, out: '04-kit-maintenance-reference.md', fn: genKitMaintenanceReference },
  ];

  let drift = false;
  for (const t of tasks) {
    const content = t.fn();
    const baseDir = t.dir || REF_DIR;
    const outPath = path.join(baseDir, t.out);
    const relOutPath = relFromRoot(outPath);
    if (isCheck) {
      const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
      if (current !== content) {
        console.error(`[drift] ${relOutPath} is out of date.`);
        drift = true;
      }
    } else {
      fs.mkdirSync(path.dirname(outPath), { recursive: true });
      fs.writeFileSync(outPath, content);
      console.log(`generated ${relOutPath}`);
    }
  }

  if (isCheck) {
    if (drift) {
      console.error('Run `node scripts/docs-generate.js` to refresh.');
      process.exit(1);
    }
    console.log('All reference docs are up to date.');
  }
}

main();
