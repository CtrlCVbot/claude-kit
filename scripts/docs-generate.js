const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const REF_DIR = path.join(ROOT, 'docs', '30-reference');
const SYNC_GUIDE_DIR = path.join(ROOT, 'docs', 'guide', 'sync');
const SRC_CLAUDE = path.join(ROOT, 'src', 'claude');
const CLAUDE_RUNTIME = path.join(ROOT, '.claude');
const PAIRING_PATH = path.join(ROOT, 'src', 'pairing-registry.json');
const TODAY = formatLocalDate(new Date());

const HEADER = (title, sources) => `# ${title}

> **Status**: Auto-generated by \`scripts/docs-generate.js\` on ${TODAY}
> **Source**: ${sources}
>
> 이 파일은 **수기 편집 금지**. 재생성: \`node scripts/docs-generate.js\`

`;

function toPosix(p) {
  return p.replace(/\\/g, '/');
}

function formatLocalDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function relFromRoot(full) {
  return toPosix(path.relative(ROOT, full));
}

function oneLine(text) {
  return String(text || '').replace(/\s+/g, ' ').trim();
}

function parseFrontmatter(md) {
  const match = md.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return {};
  const fm = {};
  const lines = match[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const colon = line.indexOf(':');
    if (colon < 0) continue;
    const key = line.slice(0, colon).trim();
    let value = line.slice(colon + 1).trim();
    if (value === '|' || value === '>') {
      const isFolded = value === '>';
      const block = [];
      i += 1;
      while (i < lines.length) {
        const nextLine = lines[i];
        if (!/^\s+/.test(nextLine)) {
          i -= 1;
          break;
        }
        block.push(nextLine.replace(/^\s+/, ''));
        i += 1;
      }
      value = (isFolded ? block.join(' ') : block.join('\n')).trim();
    }
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    fm[key] = value;
  }
  return fm;
}

function firstHeadingAndDesc(md) {
  const lines = md.split('\n');
  const hIdx = lines.findIndex(l => l.startsWith('# '));
  if (hIdx < 0) return { title: '', desc: '' };
  const title = lines[hIdx].replace(/^# /, '').trim();
  const desc = lines.slice(hIdx + 1)
    .find(l => l.trim() && !l.trim().startsWith('>') && !l.startsWith('#'));
  return { title, desc: desc ? desc.trim() : '' };
}

function parseHookHeader(js) {
  const m = js.match(/\/\*\*([\s\S]*?)\*\//);
  if (!m) return { hook: '', event: '', action: '' };
  const block = m[1];
  const pick = (re) => {
    const mm = block.match(re);
    return mm ? mm[1].trim() : '';
  };
  return {
    hook: pick(/Hook:\s*(.+)/),
    event: pick(/Event:\s*(.+)/),
    action: pick(/Action:\s*(.+)/),
  };
}

function listDomains() {
  if (!fs.existsSync(SRC_CLAUDE)) return [];
  return fs.readdirSync(SRC_CLAUDE)
    .filter(d => fs.statSync(path.join(SRC_CLAUDE, d)).isDirectory())
    .sort();
}

function walkFiles(dir, filter) {
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir)) {
    const full = path.join(dir, entry);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      out.push(...walkFiles(full, filter));
    } else if (filter(full)) {
      out.push(full);
    }
  }
  return out;
}

