function genPairing() {
  if (!fs.existsSync(PAIRING_PATH)) {
    return HEADER('Pairing Registry', '`src/pairing-registry.json`') +
      '_pairing-registry.json 미존재._\n';
  }
  const reg = JSON.parse(fs.readFileSync(PAIRING_PATH, 'utf8'));
  const entries = (reg.entries || []).slice().sort((a, b) =>
    `${a.domain}-${a.type}-${a.identity}`.localeCompare(`${b.domain}-${b.type}-${b.identity}`)
  );

  let out = HEADER('Pairing Registry', '`src/pairing-registry.json`');
  out += `전체 ${entries.length} entries. Claude ↔ Codex 자산 페어링 상태.\n\n`;

  const statusCount = entries.reduce((acc, e) => {
    acc[e.status] = (acc[e.status] || 0) + 1;
    return acc;
  }, {});
  out += `## Status 요약\n\n`;
  for (const [k, v] of Object.entries(statusCount).sort()) {
    out += `- **${k}**: ${v}\n`;
  }
  out += '\n';

  const byDomain = entries.reduce((acc, e) => {
    (acc[e.domain] ||= []).push(e);
    return acc;
  }, {});
  for (const domain of Object.keys(byDomain).sort()) {
    out += `## ${domain} 도메인\n\n`;
    out += `| Identity | Type | Status | Claude | Codex |\n|---|---|---|---|---|\n`;
    for (const e of byDomain[domain]) {
      const claude = e.claude ? `\`${toPosix(e.claude)}\`` : '—';
      const codex = e.codex ? `\`${toPosix(e.codex)}\`` : '—';
      out += `| \`${e.identity}\` | ${e.type} | ${e.status} | ${claude} | ${codex} |\n`;
    }
    out += '\n';
  }
  return out;
}

// -----------------------------------------------------------------
// Main
// -----------------------------------------------------------------

function main() {
  const isCheck = process.argv.includes('--check');
  const tasks = [
    { out: '01-commands.md', fn: genCommands },
    { out: '02-agents.md', fn: genAgents },
    { out: '03-skills.md', fn: genSkills },
    { out: '04-hooks.md', fn: genHooks },
    { out: '05-rules.md', fn: genRules },
    { out: '07-pairing-registry.md', fn: genPairing },
  ];

  let drift = false;
  for (const t of tasks) {
    const content = t.fn();
    const outPath = path.join(REF_DIR, t.out);
    if (isCheck) {
      const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
      if (current !== content) {
        console.error(`[drift] docs/30-reference/${t.out} is out of date.`);
        drift = true;
      }
    } else {
      fs.writeFileSync(outPath, content);
      console.log(`generated docs/30-reference/${t.out}`);
    }
  }

  if (isCheck) {
    if (drift) {
      console.error('Run `node scripts/docs-generate.js` to refresh.');
      process.exit(1);
    }
    console.log('All reference docs are up to date.');
  }
}

main();
